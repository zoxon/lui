import { describe, expect, it } from 'vitest'
import { renderIndex } from '@/pages/index.js'

describe('landing page', () => {
  it('renders calls to action, features, setup, and footer', () => {
    const page = renderIndex()

    expect(page).toContain('Get started')
    expect(page).toContain('Documentation')
    expect(page).toContain('GitHub')
    expect(page).toContain('TypeScript-first')
    expect(page).toContain('JSX-first')
    expect(page).toContain('No virtual DOM')
    expect(page).toContain('Lightweight runtime')
    expect(page).toContain('Safe output')
    expect(page).toContain('Theme-ready')
    expect(page).toContain('CSS tokens')
    expect(page).toContain('Server-friendly')
    expect(page).toContain('#icon-ui-github')
    expect(page).toContain('#icon-ui-typescript')
    expect(page).toContain('#icon-ui-file-jsx')
    expect(page).toContain('#icon-ui-feather')
    expect(page).toContain('#icon-ui-three')
    expect(page).toContain('#icon-ui-shield')
    expect(page).toContain('#icon-ui-palette')
    expect(page).toContain('#icon-ui-sliders')
    expect(page).toContain('#icon-ui-server')
    expect(page).toContain('width="28" height="28"')
    expect(page).toContain('git clone https://github.com/zoxon/lui.git')
    expect(page).toContain('pnpm install')
    expect(page).toContain('pnpm dev')
    expect(page).toContain('import &#39;@zoxon/lui/index.css&#39;')
    expect(page).not.toContain('Built for the web, without the weight.')
    expect(page).toContain('Open source under the MIT License.')
    expect(page).toContain('class="landing-hero"')
    expect(page).toContain('class="landing-container landing-hero__container"')
    expect(page).toContain('class="landing-container landing-quick-start__container"')
  })
})
